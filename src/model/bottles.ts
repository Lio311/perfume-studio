import type { BottleSpec, NeckId, ProfileName, SectionKind } from "./types.ts";

function ml(section: SectionKind, h: number, w: number, d: number): number {
  const k = section === "circle" || section === "oval" ? 0.62 : section === "rect" || section === "squircle" ? 0.55 : 0.48;
  return Math.max(5, Math.round((k * w * d * h) / 1000 / 5) * 5);
}

function bottle(
  id: string,
  he: string,
  en: string,
  section: SectionKind,
  profile: ProfileName,
  shoulder: number,
  h: number,
  w: number,
  d: number,
  neck: NeckId,
  softness: number,
  faceted: boolean,
  tags: string[],
  supplier?: BottleSpec["supplier"],
  capacity?: number,
): BottleSpec {
  return {
    id,
    name: { he, en },
    section,
    profile,
    shoulder,
    heightMm: h,
    widthMm: w,
    depthMm: d,
    neck,
    softness,
    faceted,
    tags,
    supplier,
    model: { type: "procedural" },
    capacityMl: capacity ?? ml(section, h, w, d),
  };
}

